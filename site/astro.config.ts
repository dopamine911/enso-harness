import starlight from '@astrojs/starlight'
import mermaid from 'astro-mermaid'
import { defineConfig } from 'astro/config'
import starlightTypeDoc from 'starlight-typedoc'
import { SITE_BASE, SITE_URL } from '../scripts/docs/site-base.ts'
import socialCard from './src/social-card.json'

/**
 * The social card link previews show (`scripts/docs/social-card.ts` renders it). Absolute, as
 * previews require, so the origin and base come from the one place both are decided.
 */
const SOCIAL_CARD_URL = `${SITE_URL}${SITE_BASE}/social-card.png`
/**
 * Its alt text, from the text it was rendered from — the record the site gate holds to the hero's
 * source — so the description cannot drift from the image.
 */
const SOCIAL_CARD_ALT = `Enso: ${socialCard.kicker}. ${socialCard.title.replace(' | ', ' ')}`

/**
 * The documentation site (#188): a PRESENTATION layer over `docs/`, never a second source.
 *
 * Content is projected in from the repository's `docs/` by `scripts/docs/site-content.ts` —
 * Starlight's `docsLoader()` can only read `src/content/docs/`, so the projection is what keeps
 * the pages beside the code they describe. The projected tree is gitignored and rebuilt on
 * every build, so the only editable copy is the one in `docs/`.
 *
 * The API reference is generated INTO this site by `starlight-typedoc`, not linked out to a
 * TypeDoc HTML build: the contracts get the site's navigation, theme and search, and a reader
 * moving from a seam page to a symbol never leaves. Its options still come from the repository's
 * `typedoc.json` — the one place the entry points and the `@group`/`@category` organisation are
 * declared — which the plugin reads itself.
 *
 * ⚠ It does NOT inherit `treatWarningsAsErrors`: measured, a `{@link}` pointing at a name that
 * does not exist renders here and exits 0. The `api-docs` gate step catches that; this build
 * renders what that step has already validated.
 *
 * `srcDir`/`outDir` stay inside `site/`; nothing this build writes leaves it.
 */
export default defineConfig({
  site: SITE_URL,
  base: SITE_BASE,
  outDir: './dist',
  // ⚠ `mermaid()` must precede `starlight()`: it rewrites the ```mermaid fences before
  // Starlight's markdown pipeline turns them into highlighted code blocks.
  integrations: [
    mermaid({ theme: 'neutral', autoTheme: true }),
    starlight({
      plugins: [
        // The API reference as NATIVE pages, not a second site behind a link (#188). TypeDoc's
        // options come from the repository's `typedoc.json`, which the plugin reads itself, so
        // the entry points, the `@group`/`@category` organisation and the fatal warnings are
        // still declared in one place.
        starlightTypeDoc({
          output: 'api',
          // ⚠ The plugin's OWN sidebar is refused (`sidebar: false`) and the tree below is
          // autogenerated from the files it writes. Its builder drops every group whose members
          // have no directory on disk — and `@group`/`@category` groups (#188) are exactly that,
          // so the API section rendered as six modules with a caret and NOTHING inside them.
          // Its own source says so: "The groups generated using the `@group` tag do not have an
          // associated directory on disk" (libs/starlight.ts).
          sidebar: false,
          // ⚠ Markdown-only options live HERE, never in `typedoc.json`: that file is also read by
          // the `api-docs` gate step, which runs TypeDoc without the markdown plugin and refuses
          // an option it does not know.
          typeDoc: {
            // One page per entry point: the `@group` sections are that page's headings and its
            // own table of contents, which IS the organisation #188 built. Per-member pages
            // scatter 300 symbols across the sidebar and lose it.
            outputFileStrategy: 'modules',
            // ⚠ Without this the generated index lands at `api/readme/`, and `/api/` — the path
            // the sidebar section and every hand-written link point at — is a 404 on the
            // published site. Measured on the deployed build, not in review.
            entryFileName: 'index',
          },
        }),
      ],
      title: 'Enso',
      description: 'The harness architecture, its seams, and the reference material generated from its source.',
      social: [{ icon: 'github', label: 'GitHub', href: 'https://github.com/dopamine911/zen-harness-foundation' }],
      // Enso's theme (helloen.so's design): Starlight's variables set in `src/styles/theme.css`,
      // the landing's own rules in `src/styles/landing.css`, imported by that page alone.
      customCss: ['./src/styles/theme.css'],
      logo: { src: './src/assets/landing/enso-smile.png', alt: '' },
      // The web app's own tab icon (`packages/web/public/favicon.png`), copied: the site and the app
      // are one product, and the mascot replaced the old "Enso-harness" mark on both.
      favicon: '/favicon.png',
      // The landing page is the site's one hero, and the override renders hello-enso's.
      components: { Hero: './src/components/LandingHero.astro' },
      // Sora, Inter and JetBrains Mono from Google Fonts, as hello-enso loads them (chosen over
      // self-hosting, 2026-09-30: every page view requests the fonts from Google).
      head: [
        { tag: 'link', attrs: { rel: 'preconnect', href: 'https://fonts.googleapis.com' } },
        { tag: 'link', attrs: { rel: 'preconnect', href: 'https://fonts.gstatic.com', crossorigin: '' } },
        {
          tag: 'link',
          attrs: {
            rel: 'stylesheet',
            href: 'https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&family=JetBrains+Mono:wght@400;500&family=Sora:wght@500;600&display=swap',
          },
        },
        // Link previews (Slack, X, LinkedIn…): Starlight already asks for a large card
        // (`twitter:card` → `summary_large_image`), and a large card with no image previews as
        // bare text. `site-links.ts` checks the image is in the build.
        { tag: 'meta', attrs: { property: 'og:image', content: SOCIAL_CARD_URL } },
        { tag: 'meta', attrs: { property: 'og:image:width', content: '1200' } },
        { tag: 'meta', attrs: { property: 'og:image:height', content: '630' } },
        { tag: 'meta', attrs: { property: 'og:image:alt', content: SOCIAL_CARD_ALT } },
        { tag: 'meta', attrs: { name: 'twitter:image', content: SOCIAL_CARD_URL } },
      ],
      // Five sections, in the order a reader needs them: what it does for a user (#437), what it
      // is, how it behaves, what it declares, how to change it. Features comes first because it
      // is the only section written for someone deciding whether to use Enso, not change it.
      //
      // ⚠ The page lists are `autogenerate`, never enumerated. A hand-written list of seam or
      // flow pages would be a maintained copy of a fact the directory already states, and the
      // first page added would silently not appear in it. The nesting is `items: [{ autogenerate }]`
      // rather than a group carrying `autogenerate` itself: Starlight removed the latter in
      // v0.39.0, and the build error — not the editor types — is what says so.
      sidebar: [
        // The origin story (#574): a page of the site's own (`src/pages/origin.astro`), not projected docs.
        { label: 'Where Enso came from', link: '/origin/' },
        { label: 'Features', items: [{ autogenerate: { directory: 'features' } }] },
        {
          label: 'Architecture',
          items: [
            { slug: 'architecture' },
            { slug: 'glossary' },
            { label: 'Seams', items: [{ autogenerate: { directory: 'seams' } }] },
            { label: 'Flows', items: [{ autogenerate: { directory: 'flows' } }] },
          ],
        },
        {
          label: 'Generated reference',
          items: [
            { slug: 'reference/flows' },
            { slug: 'reference/routes' },
            { slug: 'reference/observations' },
            { slug: 'reference/core-exports' },
            { slug: 'reference/env-and-config' },
            { slug: 'reference/decisions' },
            { slug: 'reference/verification-inventory' },
          ],
        },
        // ⚠ Autogenerated from the files the plugin writes, which keeps the URLs the module
        // paths imply (`/api/core/src/log-process/`). `flattenOutputFiles` would drop the two
        // directory groups from this tree — at the cost of `/api/coresrclog-process/`, a path
        // nobody can read or type, on a page whose whole job is being linked to.
        { label: 'API reference', items: [{ autogenerate: { directory: 'api' } }] },
        {
          label: 'Development',
          items: [
            { slug: 'verification' },
            // The repository's README: the front page until the landing took `/`.
            { slug: 'readme' },
            { label: 'Concepts', items: [{ autogenerate: { directory: 'concepts' } }] },
          ],
        },
      ],
    }),
  ],
})
